#!/usr/bin/env node
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";

const ROOT = process.cwd();

function findFoundryContracts() {
  const outDir = join(ROOT, "packages/foundry/out");
  const broadcastDir = join(ROOT, "packages/foundry/broadcast");
  if (!existsSync(outDir)) return null;

  const deployments = {};
  if (existsSync(broadcastDir)) {
    for (const scriptDir of readdirSync(broadcastDir)) {
      const scriptPath = join(broadcastDir, scriptDir);
      let entries;
      try { entries = readdirSync(scriptPath); } catch { continue; }
      for (const chainDir of entries) {
        const runFile = join(scriptPath, chainDir, "run-latest.json");
        if (!existsSync(runFile)) continue;
        try {
          const data = JSON.parse(readFileSync(runFile, "utf8"));
          const chainId = parseInt(chainDir);
          if (isNaN(chainId)) continue;
          for (const tx of data.transactions || []) {
            if (tx.transactionType === "CREATE" && tx.contractName && tx.contractAddress) {
              if (!deployments[chainId]) deployments[chainId] = {};
              deployments[chainId][tx.contractName] = tx.contractAddress;
            }
          }
        } catch { /* skip malformed */ }
      }
    }
  }

  const abis = {};
  for (const solDir of readdirSync(outDir)) {
    if (!solDir.endsWith(".sol")) continue;
    // Read every artifact in the directory, not just <dir>.json. Contracts declared
    // alongside another in one file — LocalCreditUSDC lives inside Deploy.s.sol — are
    // emitted as siblings and were silently skipped.
    let artifacts;
    try { artifacts = readdirSync(join(outDir, solDir)); } catch { continue; }
    for (const artifact of artifacts) {
      if (!artifact.endsWith(".json")) continue;
      try {
        const data = JSON.parse(readFileSync(join(outDir, solDir, artifact), "utf8"));
        if (data.abi) abis[artifact.replace(".json", "")] = data.abi;
      } catch { /* skip malformed */ }
    }
  }

  return { deployments, abis };
}

function generateTS(contracts) {
  const { deployments, abis } = contracts;
  const chains = {};
  for (const [chainId, deployed] of Object.entries(deployments)) {
    chains[chainId] = {};
    for (const [name, address] of Object.entries(deployed)) {
      if (abis[name]) {
        chains[chainId][name] = { address, abi: abis[name] };
      }
    }
  }

  if (Object.keys(chains).length === 0) {
    console.log("  No deployed contracts found. Deploy first with: just deploy");
    return null;
  }

  return `// Auto-generated by scaffold-agent — do not edit manually
// Re-generate with: just deploy

import type { Abi, Address } from "viem";

function defineContracts<
  const Contracts extends Record<
  number,
  Record<string, { address: Address; abi: Abi }>
  >,
>(contracts: Contracts): Contracts {
  return contracts;
}

const deployedContracts = defineContracts(${JSON.stringify(chains, null, 2)});

export default deployedContracts;
`;
}

function generateAbiTS(abis) {
  const vaultAbi = abis.CustomerCreditVault;
  if (!vaultAbi) {
    console.log("  CustomerCreditVault artifact not found; skipping generatedAbis.ts");
    return null;
  }
  return `// Auto-generated by scaffold-agent — do not edit manually
// Re-generate with: just deploy

import type { Abi } from "viem";

function defineAbi<const ContractAbi extends Abi>(
  abi: ContractAbi,
): ContractAbi {
  return abi;
}

export const CUSTOMER_CREDIT_VAULT_ABI = defineAbi(${JSON.stringify(vaultAbi, null, 2)});
`;
}

const contracts = findFoundryContracts();

if (!contracts) {
  console.log("  No contract artifacts found. Make sure contracts are compiled.");
  process.exit(0);
}

const generatedAbi = generateAbiTS(contracts.abis);
if (generatedAbi && existsSync(join(ROOT, "packages/nextjs"))) {
  const abiTarget = join(ROOT, "packages/nextjs/contracts/generatedAbis.ts");
  mkdirSync(dirname(abiTarget), { recursive: true });
  writeFileSync(abiTarget, generatedAbi);
  console.log("  \u2714 Generated packages/nextjs/contracts/generatedAbis.ts");
}

const ts = generateTS(contracts);
if (!ts) process.exit(0);

// packages/vite was removed; nextjs is the only consumer.
const targets = ["packages/nextjs/contracts"];

let written = false;
for (const rel of targets) {
  const target = join(ROOT, rel);
  const parent = dirname(target);
  if (existsSync(parent)) {
    mkdirSync(target, { recursive: true });
    writeFileSync(join(target, "deployedContracts.ts"), ts);
    console.log("  \u2714 Generated " + rel + "/deployedContracts.ts");
    written = true;
  }
}

if (!written) {
  mkdirSync(join(ROOT, "contracts"), { recursive: true });
  writeFileSync(join(ROOT, "contracts/deployedContracts.ts"), ts);
  console.log("  \u2714 Generated contracts/deployedContracts.ts");
}
